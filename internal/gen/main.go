// Command gen generates the Unicode width tables used by package runes.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
)

const (
	unicodeVersion = "17.0.0"
	unicodeDataURL = "https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt"
	unicodeDataSHA = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
	eastAsianURL   = "https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt"
	eastAsianSHA   = "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33"
	maxRune        = 0x10FFFF
	pageSize       = 1 << 8
)

var output = flag.String("output", "tables.go", "output file")

func main() {
	flag.Parse()

	width := make([]byte, maxRune+1)
	for i := range width {
		width[i] = 1
	}

	eastAsian := fetch(eastAsianURL, eastAsianSHA, 1<<20)
	readEastAsian(width, eastAsian)

	unicodeData := fetch(unicodeDataURL, unicodeDataSHA, 4<<20)
	readCategories(width, unicodeData)

	for r := 0xD800; r <= 0xDFFF; r++ {
		width[r] = 0
	}
	for r := 0xFDD0; r <= 0xFDEF; r++ {
		width[r] = 0
	}
	for plane := range 17 {
		width[plane<<16|0xFFFE] = 0
		width[plane<<16|0xFFFF] = 0
	}

	src := generate(width)
	formatted, err := format.Source(src)
	if err != nil {
		log.Fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile(*output, formatted, 0o666); err != nil {
		log.Fatal(err)
	}
}

func fetch(url, wantSHA string, limit int64) []byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, resp.Status)
	}

	data, err := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if err != nil {
		log.Fatal(err)
	}
	if int64(len(data)) > limit {
		log.Fatalf("GET %s: response exceeds %d bytes", url, limit)
	}
	gotSHA := fmt.Sprintf("%x", sha256.Sum256(data))
	if gotSHA != wantSHA {
		log.Fatalf("GET %s: SHA-256 %s, want %s", url, gotSHA, wantSHA)
	}
	return data
}

func readEastAsian(width []byte, data []byte) {
	scan := bufio.NewScanner(bytes.NewReader(data))
	for scan.Scan() {
		line, _, _ := strings.Cut(scan.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) != 2 {
			continue
		}
		kind := strings.TrimSpace(fields[1])
		if kind != "W" && kind != "F" {
			continue
		}
		lo, hi := codeRange(strings.TrimSpace(fields[0]))
		for r := lo; r <= hi; r++ {
			width[r] = 2
		}
	}
	if err := scan.Err(); err != nil {
		log.Fatal(err)
	}
}

func readCategories(width []byte, data []byte) {
	scan := bufio.NewScanner(bytes.NewReader(data))
	first := -1
	firstCategory := ""
	for scan.Scan() {
		fields := strings.Split(scan.Text(), ";")
		if len(fields) < 3 {
			log.Fatalf("malformed UnicodeData line %q", scan.Text())
		}
		r := codePoint(fields[0])
		name, category := fields[1], fields[2]
		switch {
		case strings.HasSuffix(name, ", First>"):
			first, firstCategory = r, category
		case strings.HasSuffix(name, ", Last>"):
			if first < 0 || category != firstCategory {
				log.Fatalf("unmatched UnicodeData range at %U", r)
			}
			setCategory(width, first, r, category)
			first = -1
		default:
			setCategory(width, r, r, category)
		}
	}
	if err := scan.Err(); err != nil {
		log.Fatal(err)
	}
	if first >= 0 {
		log.Fatal("unterminated UnicodeData range")
	}
}

func setCategory(width []byte, lo, hi int, category string) {
	switch category {
	case "Cc", "Cf", "Mn", "Me", "Zl", "Zp":
		for r := lo; r <= hi; r++ {
			width[r] = 0
		}
	}
}

func codeRange(s string) (int, int) {
	loText, hiText, found := strings.Cut(s, "..")
	lo := codePoint(loText)
	if !found {
		return lo, lo
	}
	return lo, codePoint(hiText)
}

func codePoint(s string) int {
	n, err := strconv.ParseInt(s, 16, 32)
	if err != nil || n < 0 || n > maxRune {
		log.Fatalf("invalid code point %q", s)
	}
	return int(n)
}

func generate(width []byte) []byte {
	index, pages := makePages(width)
	pages = packWidths(pages)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by go generate; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "//\n// Unicode %s:\n", unicodeVersion)
	fmt.Fprintf(&out, "// %s\n// SHA-256 %s\n", unicodeDataURL, unicodeDataSHA)
	fmt.Fprintf(&out, "// %s\n// SHA-256 %s\n\n", eastAsianURL, eastAsianSHA)
	fmt.Fprintln(&out, "package runes")
	writeBytes(&out, "widthPage", index, 16)
	writeBytes(&out, "widthData", pages, 32)
	return out.Bytes()
}

// packWidths stores four two-bit widths in each byte.
func packWidths(width []byte) []byte {
	if len(width)%4 != 0 {
		panic("width table is not pack-aligned")
	}
	packed := make([]byte, len(width)/4)
	for i, w := range width {
		if w > 3 {
			panic("width exceeds two bits")
		}
		packed[i/4] |= w << (2 * (i % 4))
	}
	return packed
}

// makePages interns equal 256-code-point pages. The returned index selects a
// page in data for every high byte in width.
func makePages(width []byte) ([]uint8, []byte) {
	if len(width)%pageSize != 0 {
		panic("width table is not page-aligned")
	}
	index := make([]uint8, len(width)/pageSize)
	seen := make(map[string]uint8)
	var data []byte
	for i := range index {
		page := width[i*pageSize : (i+1)*pageSize]
		key := string(page)
		p, ok := seen[key]
		if !ok {
			if len(data)/pageSize >= 1<<8 {
				panic("width table has more than 256 distinct pages")
			}
			p = uint8(len(data) / pageSize)
			seen[key] = p
			data = append(data, page...)
		}
		index[i] = p
	}
	return index, data
}

func writeBytes(out io.Writer, name string, data []byte, columns int) {
	fmt.Fprintf(out, "\nvar %s = [...]uint8{\n", name)
	for i, b := range data {
		if i%columns == 0 {
			fmt.Fprint(out, "\t")
		}
		fmt.Fprintf(out, "%d,", b)
		if i%columns == columns-1 || i == len(data)-1 {
			fmt.Fprintln(out)
		} else {
			fmt.Fprint(out, " ")
		}
	}
	fmt.Fprintln(out, "}")
}
